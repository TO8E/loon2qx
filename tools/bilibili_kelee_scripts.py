#!/usr/bin/env python3
"""Offline build of pinned Kelee scripts. Requires Python 3 and esbuild (build only).
Usage: python3 tools/bilibili_kelee_scripts.py [--out-dir js/BilibiliKelee]
No downloads, user arguments, BoxJS, or persistent settings at runtime.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / 'tools/upstream/bilibili-kelee'
PINNED = {
    'Bilibili_proto_request_kokoryh.js': '1b7e1d51efd960b10a22ea322630e72ecee646f2fdaad8a097c9e530fde1a857',
    'Bilibili_proto_response_kokoryh.js': 'e4a8426cffbfca85c78286126a10813051a2d1aeed018119bbabe3db5da85728',
    'Bilibili_json_kokoryh.js': '521a3974d1a485daf5750bc7b986ee5b64325480ed80da2e7d90265f4ad57090',
    'fflate-0.8.2.mjs': '8cc1f687e0159e977addb6b85e274dbd11e622cf151f4fcb7b85d49622ea43e7',
    'Sparkle-LICENSE': '8b1ba204bb69a0ade2bfcf65ef294a920f6bb361b317dba43c7ef29d96332b9b',
    'fflate-LICENSE': '805f6cb28bb8b6d3a0badd83c93bccd9671fa01a3b4b92b7042b0743325ac243',
}

def between(text, start, end):
    assert text.count(start) == text.count(end) == 1, (start, end)
    return text[text.index(start):text.index(end)]

def replace(text, old, new, count=1):
    assert text.count(old) == count, old
    return text.replace(old, new)

def emit(out: Path) -> dict:
    """Build request.js, response.js, json.js under out; return assets metadata."""
    out = Path(out)
    sources = {}
    for name, expected in PINNED.items():
        data = (UPSTREAM / name).read_bytes()
        assert hashlib.sha256(data).hexdigest() == expected, 'Upstream changed: ' + name
        sources[name] = data.decode()
    response = sources['Bilibili_proto_response_kokoryh.js']
    # Keep upstream generated protobuf descriptors, readers/writers and handlers verbatim.
    # Verified against formatted source and its schemas; these are not guessed wire tags.
    core = between(response, 'function X(', 'var R=')
    core = replace(core, between(core, 'function Ni(', 'var Xn='),
                   'function Ni(a,e){a.upList=void 0;}')
    core = replace(core, 'let{sponsorBlock:t}=a.argument,n=', 'let n=', 2)
    core = replace(core, 'ni(t)&&n.chronos&&ii(n.chronos,a.request.headers),', '', 2)
    core = replace(core, between(core, 'function ni(', 'var ri='), '')
    runtime = (ROOT / 'tools/bilibili_kelee_runtime.js').read_text()
    json_source = sources['Bilibili_json_kokoryh.js']
    # Only the three live routes used by the LPX; discard unrelated account/VIP/UI handlers.
    live = 'var ' + between(json_source, 'J=(t,e)=>', 'function re(')
    live = replace(live, 'i.room_info.short_id===255', 'i.room_info?.short_id===255')
    live += r'''
const FIXED = Object.freeze({displayUpList:'hide',purifyComment:true,optimizeRequest:true,sponsorBlock:false,logLevel:'off'});
let output = {};
try {
  const match = /^https:\/\/api\.live\.bilibili\.com\/xlive\/(?:app-interface\/v2\/index\/(feed)|app-room\/v1\/index\/(getInfoByRoom|getInfoByUser))\?/i.exec($request.url);
  if (match) {
    const state = {message: JSON.parse($response.body)};
    if (state.message.code === 0 && state.message.data) {
      const handler = match[1] ? J : match[2].toLowerCase() === 'getinfobyroom' ? G : Q;
      handler({state}, () => {});
      output = {body: JSON.stringify(state.message)};
    }
  }
} catch (_) {}
$done(output);
'''
    out.mkdir(parents=True, exist_ok=True)
    manifest = {'sources': PINNED, 'fixed': {'displayUpList': 'hide', 'purifyComment': True,
        'optimizeRequest': True, 'sponsorBlock': False, 'logLevel': 'off'}, 'outputs': {}}
    banner = '// Generated by tools/bilibili_kelee_scripts.py; upstream: kokoryh / kelee.one.\n'
    banner += '// Modified adaptation: GPL-3.0; original author kokoryh (Sparkle).\n'
    banner += '// License: tools/upstream/bilibili-kelee/Sparkle-LICENSE; QX >= 1.5.0 build 824.\n'
    banner += '// Fixed options; unary gRPC only; unsupported transports fail open.\n'
    banner += '/* Inlined fflate 0.8.2 (MIT), Copyright (c) 2023 Arjun Barrett.\n' + sources['fflate-LICENSE'] + '*/\n'
    with tempfile.TemporaryDirectory() as tmp:
        for mode in ['request', 'response', 'json']:
            name = mode + '.js'
            original = f'Bilibili_{"proto_" if mode != "json" else ""}{mode}_kokoryh.js'
            entry = Path(tmp) / (mode + '.js')
            content = live if mode == 'json' else (
                f'import {{gunzipSync as qxGunzipSync}} from {json.dumps(str(UPSTREAM / "fflate-0.8.2.mjs"))};\n'
                + f'const QX_MODE={json.dumps(mode)};\n' + core + '\n' + runtime)
            entry.write_text(content)
            result = subprocess.run(['esbuild', str(entry), '--bundle', '--format=iife',
                '--target=safari14', '--minify-whitespace', '--legal-comments=none', '--log-level=error'],
                check=True, capture_output=True, text=True)
            output = banner + result.stdout
            for banned in ['$argument', '$persistentStore', '$prefs', '$httpClient', '$utils',
                           'bsbsb.top', '/chronos/', 'DmSegMobile', 'skipSegments']:
                assert banned not in output, banned
            path = out / name
            path.write_text(output)
            manifest['outputs'][name] = {
                'source': 'https://kelee.one/Resource/JavaScript/Bilibili/' + original,
                'upstream_sha256': PINNED[original],
                'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                'adapted': True, 'path': str(path),
                'support': 'partial-best-effort-replay: no forced-H2/native-trailers' if mode == 'request' else 'binary-unary-gRPC' if mode == 'response' else 'live-JSON',
                'minimum_quantumult_x': '1.5.0 build 824',
                'auto_cookie_false_requires_build': 934,
                'recommended_quantumult_x_build': 934,
                'runtime_external_dependencies': [],
                'build_dependencies': ['python3', 'esbuild'],
            }
    return manifest['outputs']

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out-dir', type=Path, default=ROOT / 'js/BilibiliKelee')
    args = parser.parse_args()
    print(json.dumps(emit(args.out_dir), indent=2))

if __name__ == '__main__':
    main()
