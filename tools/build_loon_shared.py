#!/usr/bin/env python3
"""Build native Loon plugins from reviewed snapshots and an explicit whitelist.

No network access, private configuration, or dependency on the QX converter.
Run with --check to verify published artifacts without writing them.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
LOON = ROOT / 'loon'


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def source_sections(text):
    sections = {}
    section = ''
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if line.startswith('[') and line.endswith(']'):
            section = line[1:-1].lower()
        elif section and line and not line.startswith(('#', ';')):
            sections.setdefault(section, []).append((number, line))
    return sections


def validate_rule(rule):
    """Accept only the three native rule forms used by this narrow profile."""
    if re.fullmatch(r'DOMAIN, [a-z0-9]+(?:[.-][a-z0-9]+)*, REJECT', rule):
        return
    match = re.fullmatch(r'URL-REGEX, "([^"\r\n]+)", REJECT', rule)
    if match:
        re.compile(match[1])
        return
    if rule == ('AND, ((DOMAIN-KEYWORD, adash), '
                '(DOMAIN-SUFFIX, ut.taobao.com)), REJECT'):
        return
    raise ValueError(f'Unsupported whitelist rule: {rule}')


def select_rules(text, entries, filename):
    """Copy exact upstream rules; fail on removal or conflicting actions.

    New unselected rules and non-Rule sections never become output implicitly.
    Matching source order is preserved, including the bounded AND expression.
    """
    available = {}
    for number, line in source_sections(text).get('rule', []):
        selector = line.rsplit(',', 1)[0].strip()
        available.setdefault(selector, []).append((number, line))
    selected = []
    seen = set()
    for entry in entries:
        rule = entry['rule']
        validate_rule(rule)
        if not entry.get('apps') or not entry.get('reason'):
            raise ValueError(f'{filename}: missing provenance for {rule}')
        if rule in seen:
            raise ValueError(f'{filename}: duplicate whitelist rule: {rule}')
        seen.add(rule)
        matches = available.get(rule.rsplit(',', 1)[0].strip(), [])
        if not matches:
            raise ValueError(f'{filename}: selected rule missing: {rule}')
        if any(line != rule for _, line in matches):
            raise ValueError(f'{filename}: selected rule or action changed: {rule}')
        selected.append(dict(entry, line=matches[0][0]))
    if not selected:
        raise ValueError(f'{filename}: empty whitelist')
    return sorted(selected, key=lambda entry: entry['line'])


def render_plugin(plugin, text, selected, date):
    metadata = dict(re.findall(r'^#!([^=\n]+)=(.*)$', text, re.MULTILINE))
    lines = [f'#!name={plugin["name"]}', f'#!desc={plugin["description"]}']
    # Preserve attribution and the source's minimum client version, but never
    # copy its dependency claims, arguments, scripts, rewrites or MitM scope.
    for key in ('author', 'loon_version', 'icon'):
        lines.append(f'#!{key}={metadata[key]}')
    lines.extend([
        '#!tag=去广告, 精简',
        '#!homepage=https://github.com/TO8E/loon2qx/tree/main/loon',
        f'#!date={date}', '',
        f'# Source: {plugin["source"]}',
        f'# Upstream SHA-256: {plugin["sha256"]}',
        '# Generated by tools/build_loon_shared.py; edit loon/profile.json.',
        '', '[Rule]',
    ])
    for entry in selected:
        lines.append(f'# {", ".join(entry["apps"])} | upstream line {entry["line"]}')
        lines.append(entry['rule'])
    return ('\n'.join(lines) + '\n').encode('utf-8')


def build_artifacts(profile, snapshots):
    if profile['version'] != 1:
        raise ValueError('Unsupported profile version')
    artifacts = {}
    report = {
        'profile_date': profile['date'],
        'evidence_limit': profile['evidence_limit'],
        'plugins': [],
    }
    subscriptions = []
    for plugin in profile['plugins']:
        name = plugin['file']
        if name not in ('Block_HTTPDNS.lpx', 'BlockAdvertisers.lpx'):
            raise ValueError(f'Unexpected plugin: {name}')
        target = f'plugins/{name}'
        if target in artifacts:
            raise ValueError(f'Duplicate plugin: {name}')
        data = snapshots[name]
        text = data.decode('utf-8-sig')
        selected = select_rules(text, plugin['rules'], name)
        if sha256(data) != plugin['sha256']:
            raise ValueError(f'{name}: upstream SHA-256 changed; review snapshot before updating profile')
        output = render_plugin(plugin, text, selected, profile['date'])
        artifacts[target] = output
        sections = source_sections(text)
        report['plugins'].append({
            'file': target,
            'source': plugin['source'],
            'snapshot': f'upstream/{name}',
            'source_sha256': sha256(data),
            'output_sha256': sha256(output),
            'upstream_rule_count': len(sections.get('rule', [])),
            'selected_rule_count': len(selected),
            'removed_rule_count': len(sections.get('rule', [])) - len(selected),
            'removed_rewrite_count': len(sections.get('rewrite', [])),
            'removed_mitm': bool(sections.get('mitm')),
            'rules': selected,
        })
        subscriptions.append(f'{profile["raw_base"]}/{target}, pin=true, enabled=true')
    if len(subscriptions) != 2:
        raise ValueError('Both shared plugins are required')
    artifacts['plugin.conf'] = ('\n'.join(subscriptions) + '\n').encode('utf-8')
    artifacts['build-info.json'] = (json.dumps(report, ensure_ascii=False, indent=2) + '\n').encode('utf-8')
    return artifacts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated artifacts differ; do not write')
    args = parser.parse_args()
    try:
        profile = json.loads((LOON / 'profile.json').read_text(encoding='utf-8'))
        snapshots = {name: (LOON / 'upstream' / name).read_bytes()
                     for name in ('Block_HTTPDNS.lpx', 'BlockAdvertisers.lpx')}
        # Validate both sources before writing any generated output.
        artifacts = build_artifacts(profile, snapshots)
        if args.check:
            stale = [name for name, data in artifacts.items()
                     if not (LOON / name).is_file() or (LOON / name).read_bytes() != data]
            if stale:
                raise ValueError('Generated artifacts differ: ' + ', '.join(stale))
            print('Loon: both source hashes, whitelisted rules and all generated artifacts match.')
        else:
            for name, data in artifacts.items():
                path = LOON / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
            print('Loon: generated 2 plugins, plugin.conf and build-info.json.')
    except (OSError, ValueError, KeyError) as error:
        print(f'Loon build failed: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
